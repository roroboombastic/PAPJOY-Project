var translations = window.translations;
var availableLanguages = window.availableLanguages;

window.selectedLanguage = localStorage.getItem('papjoy-lang') || (function() {
  const locale = navigator.language || navigator.userLanguage || 'en';
  const [lang] = locale.split(/[-_]/);
  return availableLanguages[lang] ? lang : 'en';
})();
var selectedLanguage = window.selectedLanguage;

function translate(key) {
  return translations[selectedLanguage]?.[key] || translations.en[key] || key;
}

function translatePage() {
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (key) element.textContent = translate(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (key) element.placeholder = translate(key);
  });
  document.documentElement.lang = selectedLanguage;
  document.documentElement.dir = selectedLanguage === 'ar' ? 'rtl' : 'ltr';
  updateLocaleSwitcher();
  updateLanguageSwitcher();
}

function updateLanguageSwitcher() {
  const select = document.getElementById('language-selector');
  if (!select) return;
  select.value = selectedLanguage;
}

function setLanguage(lang) {
  if (!availableLanguages[lang]) return;
  selectedLanguage = lang;
  localStorage.setItem('papjoy-lang', lang);
  translatePage();
  if (typeof updateUserLinks === 'function') updateUserLinks();
}

function setRegion(regionCode) {
  selectedRegion = regionCode;
  localStorage.setItem('papjoy-region', regionCode);
  updateCurrencyFormatter();
  renderProducts();
  renderCart();
  updateCartSummary();
  updateCheckoutSummary();
  updateLocaleSwitcher();
}

window.translate = translate;
window.translatePage = translatePage;
window.updateLanguageSwitcher = updateLanguageSwitcher;
window.setLanguage = setLanguage;
window.setRegion = setRegion;
